ok = 0
def eq(a, b, msg):
    global ok
    if isinstance(a, float) or isinstance(b, float):
        assert abs(a - b) < 1e-9, f"{msg}: {a} != {b}"
    else:
        assert a == b, f"{msg}: {a} != {b}"
    ok += 1

