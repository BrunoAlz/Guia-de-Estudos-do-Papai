# Revisão independente lote m2a: m-eq1, m-sist, m-prod (data-mat.js, data-macetes.js, plus/pm2a.js)
from sympy import symbols, Eq, solve, expand, factor, Rational as R, simplify
x,y,a,b,c,m,v,i,e,F=symbols('x y a b c m v i e F')
def s1(l,r): return solve(Eq(l,r),x)
def S(eqs,vs): return solve(eqs,vs,dict=True)[0]
ok=0
def chk(c,msg):
    global ok
    assert c,msg; ok+=1
# ---- data-mat m-eq1
chk(s1(3*(x-2),2*x+5)==[11],'ex1')
chk(s1(x/2+x/3,10)==[12],'ex2')
chk(s1(x+x+1+x+2,72)==[23],'ex3')
chk(s1(5*x-7,2*x+8)==[5],'qz1')
chk(s1(x+3*x,48)==[12] and 3*12==36,'qz2')
chk(s1((x+1)/2-x/3,2)==[9],'qz3')
for alt in [3,6,15]: chk((R(alt+1,2)-R(alt,3))!=2,'qz3 distratores')
for alt in [3,15,1]: chk(5*alt-7!=2*alt+8,'qz1 distr')
# ---- data-mat m-sist
chk(S([Eq(x+y,10),Eq(x-y,4)],[x,y])=={x:7,y:3},'ex1')
chk(S([Eq(c+m,30),Eq(4*c+2*m,100)],[c,m])=={c:20,m:10},'ex2')
r=S([Eq(2*x+y,11),Eq(x-y,1)],[x,y]); chk(r=={x:4,y:3} and r[x]+r[y]==7,'qz1')
chk(S([Eq(a+e,20),Eq(3*a-e,40)],[a,e])=={a:15,e:5},'qz2')
chk(S([Eq(i+m,50),Eq(30*i+15*m,1050)],[i,m])=={i:20,m:30},'qz3')
# ---- data-mat m-prod
chk(51**2==2601 and 2500+100+1==2601 and 49*51==2499==50**2-1,'conta de cabeca')
chk(expand((x+3)**2)==x**2+6*x+9,'ex1'); chk(simplify((x**2-9)/(x+3))==x-3,'ex2')
chk((2+3)**2==25 and 2**2+3**2==13,'trap')
chk(expand((2*x-5)**2)==4*x**2-20*x+25,'qz1'); chk(factor(x**2-49)==(x-7)*(x+7),'qz2')
chk(101**2-99**2==400,'qz3')
chk(expand(3*(2*x+3*y))==6*x+9*y and factor(x**2-25)==(x-5)*(x+5) and factor(x**2+6*x+9)==(x+3)**2,'body fat')
chk(expand((a+b)*(x+y))==expand(a*x+a*y+b*x+b*y),'agrup')
# ---- plus m-eq1
chk(-3-5==-8 and -7+10==3 and 4-9==-5 and (-3)*(-4)==12 and (-2)*5==-10 and (-12)/(-3)==4,'sinais')
chk(2*3+1==7 and 2*4+1==9,'raiz')
chk(s1(x+5,12)==[7] and s1(3*x,18)==[6],'balanca')
chk(expand(3*(x-4))==3*x-12 and expand(-2*(x+5))==-2*x-10 and expand(-(x-4))==-x+4,'distrib')
chk(5*x-2*x+x==4*x and 7+3*x-2==3*x+5,'semelhantes')
chk(s1(-x,6)==[-6] and s1(-3*x,12)==[-4],'menos x')
chk(s1(5*x-3,2*x+12)==[5],'jeito balanca')
chk((34-7)//3==9 and 9*3+7==34,'desfazer')
chk(2*(3+4)==14 and 5*3-7==8 and 2*(5+4)==18==5*5-7,'testar alt')
chk(s1(x-R(2,5)*x,60)==[100],'barra')
chk(s1(3*x+3,57)==[18] and s1(5*x+10,115)==[21],'consecutivos')
chk(solve([Eq(3*F-F,30)],F)[F]==15 and 15-10==5 and 45==3*15,'idades')
chk(s1(7-2*(x-3),x+1)==[4] and 7-2*(4-3)==5,'exs1')
chk(s1(x+x+12,86)==[37] and 37+12==49,'exs2')
chk(s1(x-x/4-R(1,3)*(x-x/4),90)==[180] and s1(x-x/4-x/4,90)==[180],'exs3')
chk(s1(2*x+3,11)==[4],'erros')
# ---- plus m-sist
chk(6-4==2 and 7-3==4,'base par')
chk(S([Eq(3*x+2*y,12),Eq(x+2*y,8)],[x,y])=={x:2,y:3},'subtrair')
chk(expand(3*x+2*(20-x))==x+40 and expand(x-(20-x))==2*x-20,'parenteses')
chk(S([Eq(y,3*x),Eq(x+y,24)],[x,y])=={x:6,y:18},'j1a')
chk(S([Eq(2*x+y,13),Eq(x-y,2)],[x,y])=={x:5,y:3},'j1b')
chk(S([Eq(x+3*y,11),Eq(x+y,5)],[x,y])=={x:2,y:3},'j1c')
chk((50+8)/2==29 and (50-8)/2==21 and (40+6)/2==23 and (40-6)/2==17,'SD')
chk(S([Eq(c+m,25),Eq(4*c+2*m,70)],[c,m])=={c:10,m:15},'patas')
chk(S([Eq(2*x+y,17),Eq(x+2*y,16)],[x,y])=={x:6,y:5},'cruzado')
chk(S([Eq(x+y,14),Eq(3*x-y,10)],[x,y])=={x:6,y:8} and 21-7==14,'teste alt')
chk(S([Eq(a+m,32),Eq(m,3*a)],[a,m])=={a:8,m:24},'exs1')
chk(S([Eq(3*x+2*y,16),Eq(5*x-4*y,12)],[x,y])=={x:4,y:2},'exs2')
chk(S([Eq(c+v,40),Eq(R(1,2)*c+R(1,4)*v,14)],[c,v])=={c:16,v:24} and R(4)/R(1,4)==16,'exs3')
chk(expand((3*x+2*y)-(x-2*y))==2*x+4*y and expand(2*x-(5-x))==3*x-5,'erros')
# ---- plus m-prod
chk([n*n for n in range(11,21)]==[121,144,169,196,225,256,289,324,361,400],'quadrados')
chk(expand((x+2)*(x+3))==x**2+5*x+6 and expand(2*x*(2*x+3))==4*x**2+6*x,'base')
chk(factor(x**2-81)==(x-9)*(x+9) and factor(4*x**2-1)==(2*x-1)*(2*x+1) and factor(x**2-10*x+25)==(x-5)**2,'fat')
chk(factor(x**2+5*x+9)==x**2+5*x+9,'nao tqp')
chk(21**2==441 and 19**2==361 and 52**2==2704 and 47*53==2491 and 18*22==396,'cabeca')
chk(35**2==1225 and 65**2==4225 and 85**2==7225 and 37**2-33**2==280 and 55**2-45**2==1000,'5 e dif')
chk(17*23+17*77==1700 and 9*48-9*38==90,'evidencia')
chk(factor(x**2+14*x+49)==(x+7)**2 and factor(4*x**2-12*x+9)==(2*x-3)**2,'teste meio')
chk(expand(3*(x+2)*(x-2))==3*x**2-12 and 3-12==-9,'exs1')
chk(99**2+2*99+1==10000 and 2024**2-2023*2025==1,'exs2/3')
chk(expand((x-3)**2)==x**2-6*x+9 and expand((x+5)**2)==x**2+10*x+25 and expand(3*x*(2*x+3))==6*x**2+9*x,'erros')
print('OK',ok,'checagens')
